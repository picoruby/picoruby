# Ruby stubs for methods that exist on the target but not in any mrblib:
# C-implemented methods (GPIO, PSG::Driver.select_pwm, ...) and mruby-only
# core classes (Task, Machine, ...).
#
# Spinel compiles a whole program and refuses a call to a method no class
# defines. The RBS files already describe those methods, so this turns the
# RBS into empty Ruby definitions whose shape (arity, keywords, block) is
# right and whose body returns a default value of the declared return type.
# The `--rbs` seed then pins the real types where Spinel can represent them.

require "rbs"
require "prism"
require "rbconfig"
require "set"

module PicorubyAot
  class RubyDefs
    # full class name -> { instance: Set, singleton: Set }
    attr_reader :classes

    def initialize
      @classes = Hash.new { |h, k| h[k] = { instance: Set.new, singleton: Set.new } }
    end

    def add_files(files)
      files.each { |f| add_source(File.read(f), f) }
      self
    end

    def add_source(src, path = "(string)")
      result = Prism.parse(src, filepath: path)
      walk(result.value, [])
    end

    def defines?(klass, name, singleton: false)
      return false unless @classes.key?(klass)
      @classes[klass][singleton ? :singleton : :instance].include?(name.to_s)
    end

    def class_known?(klass)
      @classes.key?(klass)
    end

    private

    def const_name(node)
      case node
      when Prism::ConstantReadNode then node.name.to_s
      when Prism::ConstantPathNode
        parent = node.parent ? const_name(node.parent) : nil
        parent ? "#{parent}::#{node.name}" : node.name.to_s
      else
        nil
      end
    end

    # `singleton` is true inside `class << self`: a def there is a singleton
    # method of the enclosing class, as `def self.x` is. Missing that, the
    # stub generator took every such def for undefined and emitted a stub
    # beside it, and the seed landed on the stub: VFS.sanitize, declared
    # `(String) -> String`, analyzed as `(untyped) -> String`, widened.
    def walk(node, scope, singleton = false)
      return unless node
      case node
      when Prism::ClassNode, Prism::ModuleNode
        name = const_name(node.constant_path)
        full = name.start_with?("::") ? name.sub("::", "") : (scope + [name]).join("::")
        @classes[full]
        node.body&.child_nodes&.each { |c| walk(c, scope + [name]) }
        return
      when Prism::SingletonClassNode
        if node.expression.is_a?(Prism::SelfNode)
          node.body&.child_nodes&.each { |c| walk(c, scope, true) }
          return
        end
      when Prism::DefNode
        full = scope.empty? ? "Object" : scope.join("::")
        kind = singleton || node.receiver.is_a?(Prism::SelfNode) ? :singleton : :instance
        @classes[full][kind] << node.name.to_s
        return
      when Prism::CallNode
        if node.receiver.nil? && %i[attr_reader attr_writer attr_accessor].include?(node.name) && !scope.empty?
          full = scope.join("::")
          node.arguments&.arguments&.each do |a|
            next unless a.is_a?(Prism::SymbolNode)
            n = a.unescaped
            @classes[full][:instance] << n if node.name != :attr_writer
            @classes[full][:instance] << "#{n}=" if node.name != :attr_reader
          end
        end
      end
      node.child_nodes.each { |c| walk(c, scope, singleton) }
    end
  end

  class StubGenerator
    def initialize(sigfiles, ruby_defs)
      @sigfiles = sigfiles
      @defs = ruby_defs
      @aliases = {}   # "Scope::name" -> RBS type
      @decls = {}     # full name -> { kind:, super:, members: [] } in first-seen order
      @sigfiles.each { |f| load_sig(f) }
    end

    def generate
      out = +"# Generated by picoruby-aot from RBS. Do not edit.\n"
      @decls.each do |full, d|
        body = members_source(full, d)
        next if body.empty? && cruby_defines_constant?(full)
        out << open_scope(full, d) << body << close_scope(full)
      end
      out
    end

    private

    def load_sig(path)
      buf = RBS::Buffer.new(name: path, content: File.read(path))
      _, _, decls = RBS::Parser.parse_signature(buf)
      decls.each { |d| collect(d, []) }
    end

    def collect(decl, scope)
      case decl
      when RBS::AST::Declarations::Class, RBS::AST::Declarations::Module
        full = (scope + [decl.name.to_s]).join("::")
        kind = decl.is_a?(RBS::AST::Declarations::Class) ? :class : :module
        sup = kind == :class && decl.super_class ? decl.super_class.name.to_s : nil
        entry = (@decls[full] ||= { kind: kind, super: sup, members: [] })
        entry[:super] ||= sup
        decl.members.each do |m|
          case m
          when RBS::AST::Declarations::Class, RBS::AST::Declarations::Module
            collect(m, scope + [decl.name.to_s])
          when RBS::AST::Declarations::TypeAlias
            @aliases["#{full}::#{m.name}"] = m.type
          when RBS::AST::Declarations::Constant
            entry[:members] << [:const, m.name.to_s, m.type]
          when RBS::AST::Members::MethodDefinition
            entry[:members] << [:method, m]
          when RBS::AST::Members::AttrAccessor
            entry[:members] << [:attr, :attr_accessor, m.name.to_s, m.type]
          when RBS::AST::Members::AttrReader
            entry[:members] << [:attr, :attr_reader, m.name.to_s, m.type]
          when RBS::AST::Members::AttrWriter
            entry[:members] << [:attr, :attr_writer, m.name.to_s, m.type]
          end
        end
      when RBS::AST::Declarations::TypeAlias
        @aliases[decl.name.to_s] = decl.type
      when RBS::AST::Declarations::Constant
        (@decls["Object"] ||= { kind: :class, super: nil, members: [] })[:members] << [:const, decl.name.to_s, decl.type]
      end
    end

    # The constants a bare CRuby (`ruby --disable=gems`) defines, by their
    # top-level name. Only those count as CRuby's own: this process loads
    # json, rbs and prism for its own work, and their constants (JSON, YAML
    # through rbs) answered Object.const_defined? too, so the stub of
    # picoruby-json left out `JSON.generate`, which Spinel then refused,
    # and the stub of picoruby-yaml left out `YAML.load_file`, which Spinel
    # bound by name to another gem's `load_file`.
    def self.cruby_constants
      @cruby_constants ||= IO.popen([RbConfig.ruby, "--disable=gems", "-e", "puts Object.constants"], &:read).split.to_set
    end

    def cruby_defines_constant?(full)
      return false unless self.class.cruby_constants.include?(full.split("::").first)
      Object.const_defined?(full)
    rescue NameError
      false
    end

    def cruby_defines_method?(full, name, singleton)
      return false unless cruby_defines_constant?(full)
      k = Object.const_get(full)
      singleton ? k.respond_to?(name, true) : (k.method_defined?(name) || k.private_method_defined?(name))
    rescue NameError
      false
    end

    def open_scope(full, d)
      parts = full.split("::")
      s = +""
      parts.each_with_index do |p, i|
        inner = (i == parts.size - 1)
        if inner
          kw = d[:kind] == :module ? "module" : "class"
          sup = d[:kind] == :class && d[:super] && !cruby_defines_constant?(full) ? " < #{d[:super]}" : ""
          s << "#{kw} #{p}#{sup}\n"
        else
          outer = parts[0..i].join("::")
          kw = (@decls[outer] && @decls[outer][:kind] == :module) ? "module" : "class"
          kw = "module" if !@decls[outer] && cruby_defines_constant?(outer) && Object.const_get(outer).is_a?(Module) && !Object.const_get(outer).is_a?(Class)
          s << "#{kw} #{p}\n"
        end
      end
      s
    end

    def close_scope(full)
      "end\n" * full.split("::").size
    end

    def members_source(full, d)
      s = +""
      d[:members].each do |m|
        case m[0]
        when :const
          name = m[1]
          next if @defs.class_known?(full) && false
          next if cruby_defines_constant?("#{full}::#{name}")
          s << "  #{name} = #{default_for(m[2], full)}\n"
        when :attr
          _, kind, name, _type = m
          reader = kind != :attr_writer && !@defs.defines?(full, name)
          writer = kind != :attr_reader && !@defs.defines?(full, "#{name}=")
          next if !reader && !writer
          s << "  #{kind} :#{name}\n" if reader && writer && kind == :attr_accessor
          s << "  attr_reader :#{name}\n" if reader && !(reader && writer && kind == :attr_accessor)
          s << "  attr_writer :#{name}\n" if writer && !(reader && writer && kind == :attr_accessor)
        when :method
          s << method_source(full, m[1])
        end
      end
      s
    end

    def method_source(full, m)
      singleton = (m.kind == :singleton)
      name = m.name.to_s
      return "" if @defs.defines?(full, name, singleton: singleton)
      return "" if m.kind == :singleton_instance
      return "" if cruby_defines_method?(full, name, singleton)
      mt = m.overloads.first.method_type
      f = mt.type
      params = []
      f.required_positionals.each_with_index { |p, i| params << pname(p.name, "p#{i}") }
      f.optional_positionals.each_with_index { |p, i| params << "#{pname(p.name, "o#{i}")} = #{default_for(p.type, full)}" }
      params << "*#{pname(f.rest_positionals.name, 'rest')}" if f.rest_positionals
      f.trailing_positionals.each_with_index { |p, i| params << pname(p.name, "t#{i}") }
      f.required_keywords.each { |k, _| params << "#{k}:" }
      f.optional_keywords.each { |k, p| params << "#{k}: #{default_for(p.type, full)}" }
      params << "**#{f.rest_keywords.name || 'opts'}" if f.rest_keywords
      params << "&blk" if mt.block
      sig = params.empty? ? "" : "(#{params.join(', ')})"
      recv = singleton ? "self." : ""
      "  def #{recv}#{name}#{sig}\n    #{default_for(f.return_type, full)}\n  end\n"
    end

    RESERVED = %w[
      BEGIN END alias and begin break case class def defined? do else elsif end
      ensure false for if in module next nil not or redo rescue retry return
      self super then true undef unless until when while yield __FILE__ __LINE__
      __ENCODING__ __method__
    ].freeze

    # RBS parameter names may be Ruby keywords (`in`, `class`); a Ruby def
    # cannot use those, so suffix them.
    def pname(name, fallback)
      n = (name || fallback).to_s
      RESERVED.include?(n) ? "#{n}_" : n
    end

    def resolve_alias(name, scope)
      parts = scope.split("::")
      until parts.empty?
        key = (parts + [name]).join("::")
        return @aliases[key] if @aliases.key?(key)
        parts.pop
      end
      @aliases[name]
    end

    def default_for(type, scope, depth = 0)
      return "nil" if depth > 4
      case type
      when RBS::Types::Bases::Nil, RBS::Types::Bases::Void, RBS::Types::Bases::Any, RBS::Types::Bases::Top, RBS::Types::Bases::Bottom
        "nil"
      when RBS::Types::Bases::Bool then "false"
      when RBS::Types::Bases::Self then "self"
      when RBS::Types::Bases::Instance then "self"
      when RBS::Types::Bases::Class then "self.class"
      when RBS::Types::Optional then "nil"
      when RBS::Types::Union then "nil"
      when RBS::Types::Tuple then "[]"
      when RBS::Types::Record then "{}"
      when RBS::Types::Literal then type.literal.inspect
      when RBS::Types::Alias
        t = resolve_alias(type.name.to_s, scope)
        t ? default_for(t, scope, depth + 1) : "nil"
      when RBS::Types::ClassInstance
        case type.name.to_s.sub(/\A::/, "")
        when "Integer" then "0"
        when "Float" then "0.0"
        when "String" then '""'
        when "Symbol" then ":sym"
        when "TrueClass" then "true"
        when "FalseClass" then "false"
        when "NilClass" then "nil"
        when "Array" then "[]"
        when "Hash" then "{}"
        when "Range" then "(0..0)"
        when "Proc" then "nil"
        else "nil"
        end
      else
        "nil"
      end
    end
  end
end
